Function New-PKModule {
<#
.SYNOPSIS
	Creates a new PowerShell module scaffold

.DESCRIPTION
	Scaffolds a new PowerShell module with the standard directory structure,
	including manifest, root module, function folders, and supporting files.
	Creates the module root directory with subdirectories (Scripts, Private, Files),
	a module manifest (.psd1), root module file (.psm1), LICENSE, README, and .gitignore.

.NOTES
	Name    : Function_New-PKModule.ps1
	Created : 2026-07-14
	Author  : Paula Kingsley
	Version : 01.00
	History :

		** Keep this up to dayte in the Begin block! **

		v01.00 - 2026-07-14 - Created function
		v01.01 - 2026-10-09 - Fixed error in readme code block formatting

.PARAMETER Name
	Name of the new module (required)

.PARAMETER TargetPath
	Parent directory where the module folder will be created (required)

.PARAMETER License
	License type to use (default is MIT)

.PARAMETER Description
	Optional description of the module functionality

.PARAMETER Author
	Author name for the module (default is Paula Kingsley)

.EXAMPLE
	PS C:\> New-PKModule -Name MyModule -TargetPath C:\Modules

		Creates a new module named MyModule in C:\Modules\MyModule

.EXAMPLE
	PS C:\> New-PKModule -Name DataTools -TargetPath C:\Modules -License MIT -Confirm

		Creates DataTools module with confirmation prompt
#>

[CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'High')]
[OutputType([PSCustomObject])]

Param(
	[Parameter(
		Mandatory,
		Position = 0,
		ValueFromPipelineByPropertyName,
		HelpMessage = 'Name of the new module'
	)]
	[ValidateNotNullOrEmpty()]
	[ValidatePattern('^[A-Za-z0-9-]+$')]
	[string]$Name,

	[Parameter(
		Mandatory,
		Position = 1,
		ValueFromPipelineByPropertyName,
		HelpMessage = 'Parent directory for module files'
	)]
	[ValidateNotNullOrEmpty()]
	[ValidateScript({
		If (Test-Path $_ -ErrorAction SilentlyContinue) {$true} Else {Throw "Path '$_' does not exist!"}
	})]
	[string]$TargetPath,

	[Parameter(
		ValueFromPipelineByPropertyName,
		HelpMessage = 'License type (default is MIT)'
	)]
	[ValidateSet('MIT', 'Apache', 'GPL')]
	[string]$License = 'MIT',

	[Parameter(
		ValueFromPipelineByPropertyName,
		HelpMessage = 'Description of module functionality'
	)]
	[string]$Description,

	[Parameter(
		ValueFromPipelineByPropertyName,
		HelpMessage = 'Author name (if not specified, uses current user)'
	)]
	[string]$Author
)

Begin {

	# Keep version number up to date with comment help!
	[version]$Version = "01.01"

	[switch]$Abort = $false
	$Stopwatch = [System.Diagnostics.Stopwatch]::StartNew()

	$ScriptName = $MyInvocation.MyCommand.Name
	[switch]$PipelineInput = $MyInvocation.ExpectingInput
	$CurrentParams = @{} + $PSBoundParameters
	$MyInvocation.MyCommand.Parameters.keys | Where-Object { $CurrentParams.keys -notContains $_ } |
		Where-Object { Test-Path "variable:$_" } | ForEach-Object {
			$CurrentParams.Add($_, (Get-Variable $_).value)
		}
	$CurrentParams.Add("PipelineInput", $PipelineInput)
	$CurrentParams.Add("ScriptName", $ScriptName)
	$CurrentParams.Add("ScriptVersion", $Version)

	#region Helper functions
	Function _Timestamp { (Get-Date).ToString('HH:mm:ss') }

	Function _Get-Author {
		[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseApprovedVerbs', '', Justification = 'Private helper function')]
		[CmdletBinding()]
		Param()
		$CurrentUser = If ([string]::IsNullOrEmpty($env:USER)) { $env:USERNAME } Else { $env:USER }
		If ($env:OS -eq 'Windows_NT') {$CurrentUser}
		Else {
			Try {
				$DsclOutput = & dscl . -read /Users/$CurrentUser dsAttrTypeStandard:RealName 2>/dev/null
				$Lines = $DsclOutput -split "`n" | Where-Object { $_ -match '\S' }
				If ($Lines.Count -gt 1) {
					$Lines[1].Trim()
				}
				ElseIf ($Lines.Count -eq 1 -and $Lines[0] -match ':\s*(.+)') {
					$matches[1].Trim()
				}
				Else {$CurrentUser}
			}
			Catch {$CurrentUser}
		}
	}

