	Function _New-GitignoreContent {
		[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSUseApprovedVerbs', '', Justification = 'Private helper function')]
		[CmdletBinding()]
		Param()

		@"
# PowerShell
*.pssproj
*.psm1.bak

# IDE
.vscode/
.idea/
*.swp
*.swo

# OS
.DS_Store
Thumbs.db

# Module build artifacts
bin/
obj/
dist/

# Development
.env
*.log
"@
	}

	#endregion Helper functions

	$Activity = "Creating new PowerShell module scaffold"
	Write-Verbose "[$(_Timestamp)] PSBoundParameters: `n`t$($CurrentParams | Format-Table -AutoSize | Out-String)"
	Write-Verbose "[$(_Timestamp)] $ScriptName`: $Activity"

}

Process {

	If ($Abort) { Return }

	# Check if module already exists
	Write-Verbose "[$(_Timestamp)] Creating module directory structure"
	$ModulePath = Join-Path $TargetPath $Name
	If (Test-Path $ModulePath -ErrorAction SilentlyContinue) {
		Write-Error "[$(_Timestamp)] Module directory '$ModulePath' already exists"
		$Abort = $true
	}
	Else {
		Write-Verbose "[$(_Timestamp)] Module path is available: '$ModulePath'"
	}

	If ($Abort) { Return }

	If ([string]::IsNullOrEmpty($Author)) {
		$Author = _Get-Author
		Write-Verbose "[$(_Timestamp)] Author not specified, resolved to: '$Author'"
	}

	$OperationDetails = @"
Create module structure:
Name:        $Name
Description: $(If ($Description) { $Description } Else { '(none)' })
Author:      $Author
License:     $License
Folders:     Scripts, Private, Files
Files:       .psd1, .psm1, README.md, LICENSE, .gitignore
"@

	If ($PSCmdlet.ShouldProcess($ModulePath, $OperationDetails)) {

		Try {

			Write-Verbose "[$(_Timestamp)] Creating module directory structure"

			# Create root module directory
			$ModuleDir = New-Item -ItemType Directory -Path $ModulePath -Force -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created module root directory: '$($ModuleDir.FullName)'"

			# Create subdirectories
			$Subdirs = @('Scripts', 'Private', 'Files')
			Foreach ($Subdir in $Subdirs) {
				$SubdirPath = Join-Path $ModuleDir.FullName $Subdir
				$Null = New-Item -ItemType Directory -Path $SubdirPath -Force -ErrorAction Stop
				Write-Verbose "[$(_Timestamp)] Created subdirectory: '$SubdirPath'"
			}

			# Create manifest (.psd1)
			Write-Verbose "[$(_Timestamp)] Creating module manifest"
			$ManifestPath = Join-Path $ModuleDir.FullName "$Name.psd1"
			$ManifestContent = _New-ModuleManifest -ModuleName $Name -License $License -Description $Description -Author $Author
			$ManifestContent | Out-File -FilePath $ManifestPath -Encoding UTF8 -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created '$ManifestPath'"

			# Create root module (.psm1)
			Write-Verbose "[$(_Timestamp)] Creating root module file"
			$ModuleFilePath = Join-Path $ModuleDir.FullName "$Name.psm1"
			$ModuleContent = _New-ModuleRootContent -ModuleName $Name
			$ModuleContent | Out-File -FilePath $ModuleFilePath -Encoding UTF8 -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created '$ModuleFilePath'"

			# Create README.md
			Write-Verbose "[$(_Timestamp)] Creating README"
			$ReadmePath = Join-Path $ModuleDir.FullName "README.md"
			$ReadmeContent = _New-ReadmeContent -ModuleName $Name -Description $Description
			$ReadmeContent | Out-File -FilePath $ReadmePath -Encoding UTF8 -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created '$ReadmePath'"

			# Create LICENSE
			Write-Verbose "[$(_Timestamp)] Creating LICENSE file"
			$LicensePath = Join-Path $ModuleDir.FullName "LICENSE"
			$LicenseContent = _New-LicenseContent -LicenseType $License
			$LicenseContent | Out-File -FilePath $LicensePath -Encoding UTF8 -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created '$LicensePath'"

			# Create .gitignore
			Write-Verbose "[$(_Timestamp)] Creating .gitignore"
			$GitignorePath = Join-Path $ModuleDir.FullName ".gitignore"
			$GitignoreContent = _New-GitignoreContent
			$GitignoreContent | Out-File -FilePath $GitignorePath -Encoding UTF8 -ErrorAction Stop
			Write-Verbose "[$(_Timestamp)] Created '$GitignorePath'"

			Write-Verbose "[$(_Timestamp)] Module scaffold created successfully"

			[PSCustomObject]@{
				Name              = $Name
				Path              = $ModuleDir.FullName
				Description       = $Description
				Author            = $Author
				License           = $License
				Status            = "Created"
				ScriptsFolder     = (Join-Path $ModuleDir.FullName 'Scripts')
				PrivateFolder     = (Join-Path $ModuleDir.FullName 'Private')
				FilesFolder       = (Join-Path $ModuleDir.FullName 'Files')
				Timestamp         = (Get-Date)
			}
		}
		Catch {
			Write-Error "[$(_Timestamp)] Failed to create module scaffold: $_"

			[PSCustomObject]@{
				Name        = $Name
				Path        = $ModulePath
				Description = $Description
				Author      = $Author
				License     = $License
				Status      = "Failed"
				Timestamp   = (Get-Date)
			}
		}
	}
	Else {
		Write-Verbose "[$(_Timestamp)] Operation cancelled by user"

		[PSCustomObject]@{
			Name        = $Name
			Path        = $ModulePath
			Description = $Description
			Author      = $Author
			License     = $License
			Status      = "Skipped"
			Timestamp   = (Get-Date)
		}
	}
}
End {
	$Stopwatch.Stop()
	Write-Verbose "[$(_Timestamp)] $ScriptName`: Completed in $(("{0:hh'h 'mm'm 'ss's'}" -f $Stopwatch.Elapsed))"
}
} #end New-PKModule
